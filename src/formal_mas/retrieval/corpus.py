"""Build the Mathlib retrieval corpus from a dump of the elaborated Lean environment.

``scripts/extract_corpus.lean`` walks the environment after ``import Mathlib`` and writes
one raw JSON line per public, non-deprecated, non-instance theorem (pretty-printed
signature, docstring, declaration range, ``to_additive``/``to_dual`` target flags).
This module turns that dump into corpus entries m_j indexed through
t(m_j) = name ∥ signature ∥ docstring (Eqs. 4-5 of the paper).

Origin of an entry:
- ``manual``: the declaration's source range covers its own name (hand-written,
  including ``@[to_additive existing]`` counterparts and Prop structure fields);
- ``to_additive`` / ``to_dual``: generated by those attributes.
Everything else (``@[simps]``, ``@[reassoc]``, structure/equation lemmas...) is excluded.
"""

from __future__ import annotations

import json
import re
from collections import Counter
from dataclasses import asdict, dataclass
from pathlib import Path
from typing import Iterable, Iterator

SEP = " ∥ "
ORIGINS = ("manual", "to_additive", "to_dual")

# Module prefixes per project area; the longest matching prefix wins
# (so Mathlib.Data.Nat.Choose is combinatorics while Mathlib.Data.Nat is number theory).
AREA_PREFIXES: dict[str, tuple[str, ...]] = {
    "algebra": (
        "Mathlib.Algebra",
        "Mathlib.RingTheory",
        "Mathlib.GroupTheory",
        "Mathlib.FieldTheory",
        "Mathlib.LinearAlgebra",
        "Mathlib.Analysis.MeanInequalities",
        "Mathlib.Analysis.MeanInequalitiesPow",
    ),
    "number_theory": (
        "Mathlib.NumberTheory",
        "Mathlib.Data.Nat",
        "Mathlib.Data.Int",
        "Mathlib.Data.ZMod",
        "Mathlib.Data.PNat",
    ),
    "combinatorics": (
        "Mathlib.Combinatorics",
        "Mathlib.Data.Finset",
        "Mathlib.Data.Fintype",
        "Mathlib.Data.Multiset",
        "Mathlib.Data.Sym",
        "Mathlib.Data.Nat.Choose",
    ),
}
AREAS = (*AREA_PREFIXES, "other")

# Auto-generated lemma names that are never wanted, even if their range looks hand-written.
_AUTOGEN_LAST = {"injEq", "ext_iff", "sizeOf_spec", "noConfusion", "noConfusionType", "congr_simp", "eq_def"}
_AUTOGEN_RE = re.compile(r"eq_\d+")
# Universe parameter/instance lists such as `.{u_1, max u v}`.
_UNIVERSES_RE = re.compile(r"\.\{[\w\s,+()]*\}")


@dataclass(frozen=True)
class Declaration:
    """One theorem of the corpus."""

    name: str
    signature: str
    docstring: str | None
    module: str
    area: str
    origin: str
    line: int | None

    @property
    def text(self) -> str:
        """Text to embed: t(m) = name ∥ signature ∥ docstring."""
        parts = [self.name, self.signature]
        if self.docstring:
            parts.append(self.docstring)
        return SEP.join(parts)

    def to_json(self) -> dict:
        return {**asdict(self), "text": self.text}


def _collapse(s: str) -> str:
    return " ".join(s.split())


def _unescape(name: str) -> str:
    return name.replace("«", "").replace("»", "")


def area_of(module: str) -> str:
    """Project area of a module by longest component-wise prefix match."""
    parts = module.split(".")
    best, best_len = "other", 0
    for area, prefixes in AREA_PREFIXES.items():
        for p in prefixes:
            pp = p.split(".")
            if len(pp) > best_len and parts[: len(pp)] == pp:
                best, best_len = area, len(pp)
    return best


def normalize_signature(name: str, raw: str) -> str:
    """``ppSignature`` output → ``binders : type`` without the name and universe lists."""
    sig = _collapse(raw)
    for candidate in (name, _unescape(name)):
        if sig.startswith(candidate):
            sig = sig[len(candidate) :]
            break
    return _UNIVERSES_RE.sub("", sig).strip()


def is_autogenerated(name: str) -> bool:
    last = name.rsplit(".", 1)[-1]
    return last in _AUTOGEN_LAST or _AUTOGEN_RE.fullmatch(last) is not None


def written_name_matches(name: str, written: str) -> bool:
    """Whether the identifier written at the declaration site names ``name``."""
    written = _unescape(written.strip())
    if written.startswith("_root_."):
        written = written[len("_root_.") :]
    full = _unescape(name)
    return bool(written) and (full == written or full.endswith("." + written))


class SourceIndex:
    """Reads Mathlib source lines by module name (cached)."""

    def __init__(self, root: Path) -> None:
        self.root = root
        self._cache: dict[str, list[str] | None] = {}

    def lines(self, module: str) -> list[str] | None:
        if module not in self._cache:
            path = self.root.joinpath(*module.split(".")).with_suffix(".lean")
            self._cache[module] = path.read_text(encoding="utf-8").splitlines() if path.exists() else None
        return self._cache[module]

    def text_at(self, module: str, rng: list[int] | None) -> str | None:
        """Source text of a single-line range ``[line, col, end_line, end_col]`` (1-based lines)."""
        if not rng or rng[0] != rng[2]:
            return None
        lines = self.lines(module)
        if lines is None or not 1 <= rng[0] <= len(lines):
            return None
        return lines[rng[0] - 1][rng[1] : rng[3]]


def classify_origin(raw: dict, sources: SourceIndex) -> str | None:
    """``manual`` | ``to_additive`` | ``to_dual``, or ``None`` if the entry is excluded."""
    if is_autogenerated(raw["name"]):
        return None
    written = sources.text_at(raw["module"], raw.get("range"))
    if written is not None and written_name_matches(raw["name"], written):
        return "manual"
    if raw.get("to_additive"):
        return "to_additive"
    if raw.get("to_dual"):
        return "to_dual"
    return None


def read_raw(path: Path) -> tuple[dict, Iterator[dict]]:
    """Split a raw dump into its ``_meta`` header and the entry iterator."""
    f = path.open(encoding="utf-8")
    first = f.readline()
    meta = json.loads(first).get("_meta", {}) if first.strip() else {}

    def entries() -> Iterator[dict]:
        with f:
            for line in f:
                if line.strip():
                    yield json.loads(line)

    return meta, entries()


def build_corpus(raw_entries: Iterable[dict], sources: SourceIndex) -> tuple[list[Declaration], Counter]:
    """Classify, filter and normalise raw entries. Returns the corpus and exclusion counts."""
    decls: list[Declaration] = []
    excluded: Counter = Counter()
    seen: set[str] = set()
    for raw in raw_entries:
        name = raw["name"]
        if name in seen:
            excluded["duplicate"] += 1
            continue
        seen.add(name)
        if is_autogenerated(name):
            excluded["autogenerated_name"] += 1
            continue
        origin = classify_origin(raw, sources)
        if origin is None:
            excluded["other_generated"] += 1
            continue
        rng = raw.get("range")
        decls.append(
            Declaration(
                name=name,
                signature=normalize_signature(name, raw["signature_raw"]),
                docstring=_collapse(raw.get("docstring") or "") or None,
                module=raw["module"],
                area=area_of(raw["module"]),
                origin=origin,
                line=rng[0] if rng else None,
            )
        )
    decls.sort(key=lambda d: (d.module, d.line or 0, d.name))
    return decls, excluded


def write_jsonl(decls: Iterable[Declaration], out: Path) -> int:
    out.parent.mkdir(parents=True, exist_ok=True)
    n = 0
    with out.open("w", encoding="utf-8", newline="\n") as f:
        for d in decls:
            f.write(json.dumps(d.to_json(), ensure_ascii=False) + "\n")
            n += 1
    return n


def load_jsonl(path: Path) -> list[dict]:
    with path.open(encoding="utf-8") as f:
        return [json.loads(line) for line in f if line.strip()]


def corpus_stats(records: list[dict]) -> dict:
    """Size, mean text/signature length (characters), docstring share, per-area and per-origin counts."""
    n = len(records)
    by_area = {a: sum(1 for r in records if r["area"] == a) for a in AREAS}
    by_origin = {o: sum(1 for r in records if r["origin"] == o) for o in ORIGINS}
    if n == 0:
        return {"n": 0, "mean_text_chars": 0.0, "mean_signature_chars": 0.0,
                "docstring_pct": 0.0, "by_area": by_area, "by_origin": by_origin}
    return {
        "n": n,
        "mean_text_chars": sum(len(r["text"]) for r in records) / n,
        "mean_signature_chars": sum(len(r["signature"]) for r in records) / n,
        "docstring_pct": 100.0 * sum(1 for r in records if r["docstring"]) / n,
        "by_area": by_area,
        "by_origin": by_origin,
    }
