"""Retriever: Lean subgoal → top-k Mathlib lemmas (Eqs. 4-5), plus name suggestions.

Method (config/pipeline.yaml → retrieval, chosen on Q-dev in Phase 1.4): reciprocal rank
fusion of BM25 and the dense model `embeddings.selected` (config/models.yaml), over the
index of the FULL corpus (data/index/full). The query is the subgoal rewritten in the
format of the reference queries Q (`binders : type`), so the Phase 1.4 numbers apply.

Generic second query (`generic_query`, adopted 2026-10-19 after a manual error analysis,
not after Q-test numbers): concrete carriers such as ℝ in the query push the generic
lemmas olympiad proofs need (`[Semiring R] … (a : R)`, e.g. two_mul_le_add_sq) behind
Real.* lemmas, in BM25 and in the dense model. When the query binds no type variable,
a second query with the concrete carrier replaced by `R` (`generalize_query`) is run
through the same rankers and the four rankings are fused by RRF.

Index layout under `index_dir`:
    bm25/      BM25 matrix, idf, vocabulary + lemmas.json (names and signatures, corpus order)
    <model>/   index.faiss, names.json, meta.json (from scripts/build_index.py --from-vectors)
    names_extra.json  theorem names of Init/Std/Batteries, used ONLY by `suggest_names`
               (never searched, so the Phase 1.4 evaluation on Mathlib still holds)

Degradation, never raising:
    hybrid  → BM25 + dense (normal mode)
    bm25    → torch/faiss/the dense index/its model are missing or mismatched: lexical only
    none    → no lexical index (nor corpus to build it from): every query returns []
Every degradation is logged as a JSON `retriever_warning` event.
"""

from __future__ import annotations

import difflib
import hashlib
import json
import logging
import re
from collections import defaultdict
from pathlib import Path
from typing import Sequence

import numpy as np

from formal_mas.agents.contracts import LemmaHit
from formal_mas.config import ROOT, load_models, load_pipeline
from formal_mas.retrieval.bm25 import B as BM25_B
from formal_mas.retrieval.bm25 import BM25
from formal_mas.retrieval.bm25 import K1 as BM25_K1
from formal_mas.retrieval.corpus import is_autogenerated
from formal_mas.retrieval.evaluate import RRF_K

LOG = logging.getLogger(__name__)
BM25_DIR = "bm25"
EXTRA_NAMES_FILE = "names_extra.json"
EXTRA_NAME_PREFIXES = ("Init", "Std", "Batteries")

_DECL_RE = re.compile(r"^\s*(?:(?:private|protected|nonrec)\s+)*(?:theorem|lemma)\s+\S+\s*|^\s*example\s*")
_INST_RE = re.compile(r"^inst\S*✝$")
CONCRETE_TYPES = ("ℝ", "ℚ", "ℤ", "ℂ", "ℕ")
_TYPE_BINDER_RE = re.compile(r"[{(\[]\s*[^:{}()\[\]]+:\s*(?:Type|Sort)\b")
# A concrete type as a whole token: not part of a name (Real.ℝ…), ℝ≥0 or ℕ+.
_CONCRETE_RE = {t: re.compile(rf"(?<![\w.]){re.escape(t)}(?![\w≥+])") for t in CONCRETE_TYPES}


def _event(level: int, event: str, **detail) -> None:
    LOG.log(level, json.dumps({"event": event, **detail}, ensure_ascii=False))


def names_sha(names: Sequence[str]) -> str:
    return hashlib.sha256("\n".join(names).encode("utf-8")).hexdigest()


# ---------------------------------------------------------------------------
# Query construction


def _binder(hyp: str) -> str | None:
    """`a b : T` → `(a b : T)`; `inst✝ : C α` → `[C α]`; `x : T := v` → `(x : T)`."""
    if " : " not in hyp:
        return None
    names, typ = hyp.split(" : ", 1)
    typ = typ.split(" := ", 1)[0].strip()
    names = names.strip()
    if all(_INST_RE.match(n) for n in names.split()):
        return f"[{typ}]"
    return f"({names} : {typ})"


def goal_to_query(subgoal: str) -> str:
    """Rewrite a Lean subgoal in the format of the reference queries Q (`binders : type`).

    Accepts a pretty-printed goal state (hypotheses, then `⊢ goal`; only the first goal is
    used) or a declaration/statement (`theorem foo (x : ℕ) : P x := ...` → `(x : ℕ) : P x`).
    """
    text = subgoal.strip()
    if "⊢" not in text:
        text = _DECL_RE.sub("", text, count=1)
        text = text.split(":=", 1)[0]
        return " ".join(text.split())

    hyps: list[str] = []
    goal: list[str] = []
    for line in text.splitlines():
        if goal:
            if line[:1].isspace() and line.strip():
                goal.append(line.strip())  # continuation of the target
                continue
            break  # end of the first goal
        stripped = line.strip()
        if not stripped or stripped.startswith("case "):
            continue
        if stripped.startswith("⊢"):
            goal.append(stripped[1:].strip())
        elif line[:1].isspace() and hyps:
            hyps[-1] += " " + stripped  # continuation of a hypothesis
        else:
            hyps.append(stripped)
    binders = [b for b in (_binder(" ".join(h.split())) for h in hyps) if b]
    target = " ".join(" ".join(goal).split())
    return " ".join([*binders, ":", target]) if binders else target


def generalize_query(query: str) -> str | None:
    """Second query aimed at generic lemmas: concrete carriers → type variable `R`.

    ℝ, ℚ, ℤ and ℂ are replaced; ℕ only when it is the sole concrete type (otherwise it is
    usually an index or exponent, which generic lemmas keep as ℕ). Returns None when there
    is nothing to generalise: no concrete type, or the query already binds a type variable.
    """
    if _TYPE_BINDER_RE.search(query):
        return None
    present = [t for t in CONCRETE_TYPES if _CONCRETE_RE[t].search(query)]
    if not present:
        return None
    var = "α" if re.search(r"(?<!\w)R(?!\w)", query) else "R"
    for t in [t for t in present if t != "ℕ"] or ["ℕ"]:
        query = _CONCRETE_RE[t].sub(var, query)
    return query


