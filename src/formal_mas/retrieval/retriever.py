# Lexical index (persisted BM25 + names/signatures)


def build_lexical_index(corpus_path: Path, out_dir: Path) -> None:
    """Build BM25 over t(m) = name ∥ signature ∥ docstring and save it with the lemma table."""
    names, signatures, texts = [], [], []
    with corpus_path.open(encoding="utf-8") as f:
        for line in f:
            r = json.loads(line)
            names.append(r["name"])
            signatures.append(r["signature"])
            texts.append(r["text"])
    bm25 = BM25(texts)
    del texts
    bm25.save(out_dir)
    (out_dir / "lemmas.json").write_text(json.dumps({"names": names, "signatures": signatures}, ensure_ascii=False),
                                         encoding="utf-8")
    (out_dir / "meta.json").write_text(json.dumps({
        "corpus": corpus_path.name, "size": len(names), "corpus_names_sha256": names_sha(names),
        "tokenizer": "formal_mas.retrieval.bm25.tokenize", "k1": BM25_K1, "b": BM25_B,
    }, indent=2), encoding="utf-8")


def build_extra_names(raw_path: Path, out_path: Path, lean_meta: dict | None = None) -> int:
    """Post-process the dump of scripts/extract_names.lean into `names_extra.json`
    (drops auto-generated equation/congruence lemmas, like the corpus does)."""
    names = []
    with raw_path.open(encoding="utf-8") as f:
        for line in f:
            r = json.loads(line)
            if not is_autogenerated(r["name"]):
                names.append(r["name"])
    names = sorted(set(names))
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(json.dumps({
        "prefixes": list(EXTRA_NAME_PREFIXES),
        "excluded": "Lean.* namespace, private, internal, deprecated, instances, auto-generated",
        "use": "suggest_names only (not in the BM25/dense search index)",
        **({"lean": lean_meta} if lean_meta else {}),
        "size": len(names), "names": names,
    }, ensure_ascii=False), encoding="utf-8")
    return len(names)


class NameIndex:
    """Lexical suggestions for `unknown identifier X` (handles Lean 3 casing such as nat.foo)."""

    def __init__(self, names: Sequence[str]):
        self.names = names
        self._by_lower: dict[str, list[str]] = defaultdict(list)
        self._by_last: dict[str, list[str]] = defaultdict(list)
        for n in names:
            self._by_lower[n.lower()].append(n)
            self._by_last[n.rsplit(".", 1)[-1].lower()].append(n)
        self._lasts = list(self._by_last)

    def suggest(self, ident: str, n: int = 5) -> list[str]:
        ident = ident.strip().lstrip("@").removeprefix("_root_.")
        if not ident:
            return []
        low = ident.lower()
        ns, _, last = low.rpartition(".")

        def rank(m: str) -> tuple:  # names in the identifier's namespace first, then shortest
            return m.lower().rpartition(".")[0] != ns, len(m), m

        out: list[str] = list(self._by_lower.get(low, []))
        out += sorted(self._by_last.get(last, []), key=rank)
        if len(out) < n:
            close = difflib.get_close_matches(last, self._lasts, n=n, cutoff=0.85)
            out += sorted((m for c in close for m in self._by_last[c]), key=rank)
        return list(dict.fromkeys(out))[:n]


# ---------------------------------------------------------------------------
# Retriever


class Retriever:
    """`retrieve(subgoal) → [LemmaHit]` with RRF(BM25, dense). Never raises."""

    def __init__(self, index_dir: Path | None = None, pipeline_cfg: dict | None = None,
                 models_cfg: dict | None = None, encoder=None, build_missing_bm25: bool = True):
        self.warnings: list[dict] = []
        self.bm25: BM25 | None = None
        self.names: list[str] = []
        self.signatures: list[str] = []
        self._dense = None  # (faiss index, names, encoder, spec)
        self._name_index: NameIndex | None = None
        self._sig_by_name: dict[str, str] | None = None
        self.index_dir: Path | None = None
        try:
            cfg = (pipeline_cfg if pipeline_cfg is not None else load_pipeline()).get("retrieval", {})
            self.method = cfg.get("method", "rrf")
            self.k = int(cfg.get("k", 16))
            self.depth = int(cfg.get("depth", 100))
            self.rrf_k = int(cfg.get("rrf_k", RRF_K))
            self.query_instruction = bool(cfg.get("query_instruction", True))
            self.generic_query = bool(cfg.get("generic_query", False))
            self.n_suggestions = int(cfg.get("suggestions", 5))
            index_dir = Path(index_dir) if index_dir is not None else ROOT / cfg.get("index_dir", "data/index/full")
            self.index_dir = index_dir
            self._load_lexical(index_dir, build_missing_bm25)
            if self.method in ("rrf", "dense") and self.bm25 is not None:
                self._load_dense(index_dir, models_cfg, encoder)
        except Exception as exc:  # noqa: BLE001 — degrade, never crash
            self._warn("init_failed", error=repr(exc))
            self.method, self.k, self.depth, self.rrf_k = "rrf", 16, 100, RRF_K
            self.query_instruction, self.generic_query, self.n_suggestions = True, False, 5

    # -- loading ------------------------------------------------------------

    def _warn(self, reason: str, **detail) -> None:
        entry = {"reason": reason, **detail}
        self.warnings.append(entry)
        _event(logging.WARNING, "retriever_warning", **entry)

    def _load_lexical(self, index_dir: Path, build_missing: bool) -> None:
        folder = index_dir / BM25_DIR
        if not (folder / "lemmas.json").exists():
            corpus = index_dir.parent / "corpus.jsonl"
            if not (build_missing and corpus.exists()):
                self._warn("lexical_index_missing", path=str(folder))
                return
            _event(logging.INFO, "retriever_info", message="building BM25 index", corpus=str(corpus))
            build_lexical_index(corpus, folder)
        try:
            lemmas = json.loads((folder / "lemmas.json").read_text(encoding="utf-8"))
            self.names, self.signatures = lemmas["names"], lemmas["signatures"]
            self.bm25 = BM25.load(folder)
        except Exception as exc:  # noqa: BLE001
            self.bm25, self.names, self.signatures = None, [], []
            self._warn("lexical_index_unreadable", path=str(folder), error=repr(exc))

    def _load_dense(self, index_dir: Path, models_cfg: dict | None, encoder) -> None:
        try:
            emb = (models_cfg if models_cfg is not None else load_models())["embeddings"]
            key = emb["selected"]
            folder = index_dir / key
            if not (folder / "index.faiss").exists():
                self._warn("dense_index_missing", model=key, path=str(folder))
                return
            meta = json.loads((folder / "meta.json").read_text(encoding="utf-8"))
            if meta.get("embedding_key") != key or meta.get("hf_id") != emb["candidates"][key]["hf_id"]:
                self._warn("dense_index_model_mismatch", models_yaml=key, index=meta.get("embedding_key"))
                return
            import faiss

            dense_names = json.loads((folder / "names.json").read_text(encoding="utf-8"))
            if encoder is None:
                from formal_mas.retrieval.encoders import EmbeddingSpec, Encoder

                encoder = Encoder(EmbeddingSpec(key=key, **emb["candidates"][key]))
            self._dense = (faiss.read_index(str(folder / "index.faiss")), dense_names, encoder)
        except ImportError as exc:
            self._warn("dense_libraries_missing", error=repr(exc))
        except Exception as exc:  # noqa: BLE001
            self._warn("dense_unavailable", error=repr(exc))

    @property
    def mode(self) -> str:
        if self.bm25 is None:
            return "none"
        if self.method == "bm25" or self._dense is None:
            return "bm25"
        return "dense" if self.method == "dense" else "hybrid"

    # -- querying -----------------------------------------------------------

    def _bm25_ranking(self, query: str) -> list[tuple[str, float]]:
        return [(self.names[i], s) for i, s in self.bm25.top(query, self.depth)]

    def _dense_ranking(self, query: str) -> list[tuple[str, float]]:
        index, names, encoder = self._dense
        q = encoder.spec.query_text(query, self.query_instruction)
        scores, ids = index.search(np.asarray(encoder.encode([q]), dtype=np.float32), self.depth)
        return [(names[i], float(s)) for i, s in zip(ids[0], scores[0]) if i >= 0]

    def _signature(self, name: str) -> str:
        if self._sig_by_name is None:
            self._sig_by_name = dict(zip(self.names, self.signatures))
        return self._sig_by_name.get(name, "")

    def retrieve(self, subgoal: str, k: int | None = None) -> list[LemmaHit]:
        """Top-k lemmas for a Lean subgoal (goal state or statement); [] on any failure."""
        k = self.k if k is None else k
        mode = self.mode
        if mode == "none":
            return []
        try:
            query = goal_to_query(subgoal)
            if not query:
                return []
            queries = [query]
            if self.generic_query and (generic := generalize_query(query)):
                queries.append(generic)
            rankings = []
            for q in queries:
                if mode in ("bm25", "hybrid"):
                    rankings.append(self._bm25_ranking(q))
                if mode in ("dense", "hybrid"):
                    rankings.append(self._dense_ranking(q))
            ranked = rankings[0] if len(rankings) == 1 else self._rrf(rankings)
            return [LemmaHit(name=n, signature=self._signature(n), score=s) for n, s in ranked[:k]]
        except Exception as exc:  # noqa: BLE001 — degrade, never crash
            self._warn("retrieve_failed", mode=mode, error=repr(exc))
            if mode != "bm25" and self.bm25 is not None:
                try:
                    ranked = self._bm25_ranking(goal_to_query(subgoal))
                    return [LemmaHit(name=n, signature=self._signature(n), score=s) for n, s in ranked[:k]]
                except Exception:  # noqa: BLE001
                    pass
            return []

    def _rrf(self, rankings: list[list[tuple[str, float]]]) -> list[tuple[str, float]]:
        scores: dict[str, float] = {}
        for ranked in rankings:
            for i, (name, _) in enumerate(ranked, start=1):
                scores[name] = scores.get(name, 0.0) + 1 / (self.rrf_k + i)
        return sorted(scores.items(), key=lambda kv: (-kv[1], kv[0]))

    def _extra_names(self) -> list[str]:
        if self.index_dir is None:
            return []
        path = self.index_dir / EXTRA_NAMES_FILE
        try:
            return json.loads(path.read_text(encoding="utf-8"))["names"]
        except FileNotFoundError:
            self._warn("extra_names_missing", path=str(path))
        except Exception as exc:  # noqa: BLE001
            self._warn("extra_names_unreadable", path=str(path), error=repr(exc))
        return []

    def suggest_names(self, ident: str, n: int | None = None) -> list[str]:
        """Real names close to an unknown identifier: Mathlib (the corpus) plus the theorems of
        Init/Std/Batteries (names_extra.json, suggestions only). [] on any failure."""
        try:
            if self._name_index is None:
                self._name_index = NameIndex([*self.names, *self._extra_names()])
            if not self._name_index.names:
                return []
            return self._name_index.suggest(ident, self.n_suggestions if n is None else n)
        except Exception as exc:  # noqa: BLE001
            self._warn("suggest_failed", error=repr(exc))
            return []
