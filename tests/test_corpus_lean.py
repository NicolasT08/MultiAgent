"""Integration test: real Lean extraction on one Mathlib module (`pytest -m slow`, ~1 min)."""

from __future__ import annotations

import json
import subprocess
import sys
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[1]
MATHLIB = ROOT / "lean_project" / ".lake" / "packages" / "mathlib"
MODULE = "Mathlib.Algebra.BigOperators.Group.Finset.Basic"

pytestmark = [
    pytest.mark.slow,
    pytest.mark.skipif(not MATHLIB.exists(), reason="lean_project/ with Mathlib not built"),
]


@pytest.fixture(scope="module")
def corpus(tmp_path_factory) -> dict[str, dict]:
    out = tmp_path_factory.mktemp("index")
    subprocess.run(
        [sys.executable, str(ROOT / "scripts" / "build_index.py"), "--module-prefix", MODULE, "--out", str(out)],
        check=True,
        timeout=900,
    )
    meta = json.loads((out / "corpus_meta.json").read_text(encoding="utf-8"))
    assert meta["extraction"]["module_prefix"] == MODULE
    assert meta["extraction"]["pp_options"]["pp.universes"] is False
    with (out / "corpus.jsonl").open(encoding="utf-8") as f:
        return {r["name"]: r for r in map(json.loads, f)}


def test_origins_on_real_module(corpus):
    assert corpus["Finset.prod_range_succ"]["origin"] == "manual"
    assert corpus["Finset.sum_range_succ"]["origin"] == "to_additive"
    assert all(r["module"] == MODULE for r in corpus.values())


def test_signatures_are_clean(corpus):
    sig = corpus["Finset.sum_range_succ"]["signature"]
    assert sig.startswith("{M : Type")
    assert "∑ x ∈ Finset.range (n + 1), f x" in sig
    assert not any(".{" in r["signature"] or "\n" in r["signature"] for r in corpus.values())


def test_no_autogenerated_names(corpus):
    assert not any(n.endswith((".injEq", ".ext_iff", ".eq_def")) for n in corpus)
