TOY_LINES = [
    "@[to_additive]",                                       # 1
    "theorem prod_foo (f : ℕ → M) : True := trivial",       # 2
    "@[simps]",                                             # 3
    "def myEquiv : A ≃ B := sorry",                         # 4
    "theorem «exists» : True := trivial",                   # 5
    "theorem _root_.root_thm : True := trivial",            # 6
    "@[reassoc] theorem comp_id' : True := trivial",        # 7
    "@[to_dual] theorem le_top' : True := trivial",         # 8
    "@[to_additive existing] theorem prod_bar : True := trivial",  # 9
    "theorem sum_bar : True := trivial",                    # 10
]
MODULE = "Mathlib.Algebra.Toy"


def rng(line: int, token: str) -> list[int]:
    col = TOY_LINES[line - 1].index(token)
    return [line, col, line, col + len(token)]


def raw(name, range_, *, to_additive=False, to_dual=False, sig=None, doc=None, module=MODULE):
    return {
        "name": name, "module": module, "range": range_, "docstring": doc,
        "signature_raw": sig or f"{name} : True",
        "to_additive": to_additive, "to_dual": to_dual,
    }


RAW = [
    raw("Toy.prod_foo", rng(2, "prod_foo"), sig="Toy.prod_foo.{u_1} {M : Type u_1} (f : ℕ → M) :\n  True",
        doc="Product\n  lemma."),
    raw("Toy.sum_foo", rng(1, "to_additive"), to_additive=True),
    raw("Toy.myEquiv_apply", rng(4, "myEquiv")),
    raw("Toy.exists", rng(5, "«exists»")),
    raw("root_thm", rng(6, "_root_.root_thm")),
    raw("Toy.comp_id'_assoc", rng(7, "comp_id'")),
    raw("Toy.le_top'_dual", rng(8, "to_dual"), to_dual=True),
    raw("Toy.sum_bar", rng(10, "sum_bar"), to_additive=True),  # existing counterpart: hand-written
    raw("Toy.Foo.mk.injEq", None),
    raw("Toy.foo.eq_1", rng(2, "prod_foo")),
    raw("Toy.prod_foo", rng(2, "prod_foo")),  # duplicate
    raw("Toy.no_source", [1, 0, 1, 3], module="Mathlib.Missing"),
]


