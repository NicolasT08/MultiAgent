def test_read_raw_and_roundtrip(tmp_path: Path, sources):
    raw_path = tmp_path / "raw.jsonl"
    lines = [json.dumps({"_meta": {"pp_options": {"pp.universes": False}}})] + [json.dumps(r) for r in RAW]
    raw_path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    meta, entries = read_raw(raw_path)
    assert meta["pp_options"] == {"pp.universes": False}
    decls, _ = build_corpus(entries, sources)

    out = tmp_path / "corpus.jsonl"
    assert write_jsonl(decls, out) == 6
    records = load_jsonl(out)
    assert all(set(r) >= {"name", "signature", "docstring", "origin", "area", "text"} for r in records)

    stats = corpus_stats(records)
    assert stats["n"] == 6
    assert stats["by_origin"] == {"manual": 4, "to_additive": 1, "to_dual": 1}
    assert stats["by_area"]["algebra"] == 6
    assert stats["docstring_pct"] == pytest.approx(100 / 6)


def test_stats_empty():
    stats = corpus_stats([])
    assert stats["n"] == 0 and stats["by_origin"] == {"manual": 0, "to_additive": 0, "to_dual": 0}
